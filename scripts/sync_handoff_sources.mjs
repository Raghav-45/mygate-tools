// Package the standalone tools verbatim inside isolated factories. Only the
// surrounding adapter is new; queries, calculations and workbook styles stay intact.
import { readFileSync, writeFileSync, copyFileSync, cpSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const target = path.join(root, 'mygate-handoff-tool')
mkdirSync(path.join(target, 'generators'), { recursive: true })
const runners = {
  dump: 'run: (p) => { activeScanAbort = false; return runMasterDumpExport(p) }, abort: () => { activeScanAbort = true }',
  report: 'run: (p) => { activeScanAbort = false; return runFullReportScan(p) }, abort: () => { activeScanAbort = true }',
  summary: 'run: (p) => { currentScanAbort = false; return runSummaryScan(p.year, p.month, p.requestDelayMs / 1000) }, abort: () => { currentScanAbort = true }',
  analysis: 'run: runAnalysisBuild, abort: () => {}',
}
for (const [slot, exports] of Object.entries(runners)) {
  const source = readFileSync(path.join(root, `mygate-${slot}-tool/background.js`), 'utf8')
  writeFileSync(path.join(target, `generators/${slot}.js`),
    `// Generated by scripts/sync_handoff_sources.mjs. Do not edit the embedded source.\n` +
    `self.HandoffGenerators ||= {};\nself.HandoffGenerators.${slot} = function (chrome, importScripts) {\n` +
    source + `\nreturn { ${exports} };\n};\n`)
}
for (const file of ['engine.js', 'constants.js', 'popup.css']) {
  copyFileSync(path.join(root, 'mygate-analysis-tool', file), path.join(target, file))
}
copyFileSync(path.join(root, 'mygate-report-tool/exceljs.min.js'), path.join(target, 'exceljs.min.js'))
for (const dir of ['icons', 'chart_templates']) {
  cpSync(path.join(root, 'mygate-analysis-tool', dir), path.join(target, dir), { recursive: true })
}
// Outlook assets are owned by the handoff extension. Keeping their source here
// lets the retired extension be removed completely.
